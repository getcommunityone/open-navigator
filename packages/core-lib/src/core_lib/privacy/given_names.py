"""The aggregate given-name list the name redactor uses (#1468), and the command that rebuilds it.

The list is the one speaker introductions already use to tell a name from an ordinary word (#1231, #1245): every
lower-case given name carried by at least 4 people in the person master (``gold.mdm_person.given_name_norm``), plus
every first name that at least 2 current officials share (``public.person_government``). It is an aggregate of first
names only. No surname, person or place is in it, so it is safe to keep in the repository.

It also copies the reviewed public-figure allow-list (the ``trending_term_public_figure`` dbt seed) into
``_public_figures_data.py``, because the deployed API has no ``dbt_project/``.

Rebuild from the local warehouse (reads ``OPEN_NAVIGATOR_DATABASE_URL``; never Neon)::

    python -m core_lib.privacy.given_names --write
"""

from __future__ import annotations

import argparse
import os
import textwrap
from functools import lru_cache
from pathlib import Path

DATA_FILE = Path(__file__).with_name("_given_names_data.py")
FIGURES_FILE = Path(__file__).with_name("_public_figures_data.py")
SEED = Path(__file__).resolve().parents[5] / "dbt_project" / "seeds" / "trending_term_public_figure.csv"

# Words the person master carries as a "given name" that are not names in running text.
JUNK = frozenset(
    """
    city park school christian unknown none null test council county board church street state mr mrs ms dr
    """.split()
)

EXPORT_SQL = """
select g from (
    select given_name_norm as g
    from gold.mdm_person
    where given_name_norm ~ '^[a-z]{2,}$'
    group by given_name_norm
    having count(*) >= 4
    union
    select split_part(lower(btrim(full_name)), ' ', 1)
    from public.person_government
    where coalesce(is_current, true) and split_part(lower(btrim(full_name)), ' ', 1) ~ '^[a-z]{2,}$'
    group by 1
    having count(*) >= 2
) as s
order by 1
"""


@lru_cache(maxsize=1)
def given_names() -> frozenset[str]:
    """The stored list, lower-case."""
    from core_lib.privacy._given_names_data import GIVEN_NAMES

    return frozenset(GIVEN_NAMES.split()) - JUNK


def render(names: list[str]) -> str:
    body = textwrap.fill(" ".join(sorted(set(names) - JUNK)), width=116)
    return (
        '"""Generated by ``python -m core_lib.privacy.given_names --write`` (#1468). Do not edit by hand."""\n\n'
        'GIVEN_NAMES = """\n' + body + '\n"""\n'
    )


def render_figures(figures: frozenset[str]) -> str:
    """The reviewed public-figure allow-list, copied from the dbt seed so the API has it without dbt_project/."""
    body = "\n".join(f"        {f!r}," for f in sorted(figures))
    return (
        '"""Generated by ``python -m core_lib.privacy.given_names --write`` from\n'
        'dbt_project/seeds/trending_term_public_figure.csv (#1468). Do not edit by hand; edit the seed."""\n\n'
        "PUBLIC_FIGURES = frozenset(\n    {\n" + body + "\n    }\n)\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="Rewrite the stored list (default: print a count).")
    args = parser.parse_args(argv)
    if args.write and SEED.is_file():
        from core_lib.privacy.names import load_public_figures_csv

        FIGURES_FILE.write_text(render_figures(load_public_figures_csv(SEED)), encoding="utf-8")
        print(f"wrote {FIGURES_FILE}")
    from sqlalchemy import create_engine, text

    url = os.environ.get("OPEN_NAVIGATOR_DATABASE_URL")
    if not url:
        raise SystemExit("OPEN_NAVIGATOR_DATABASE_URL is not set")
    if "neon" in url:
        raise SystemExit("refusing to read Neon: run against the local warehouse")
    engine = create_engine(url.replace("postgresql://", "postgresql+psycopg2://", 1) if url.startswith("postgresql://") else url)
    with engine.connect() as conn:
        conn.execute(text("set statement_timeout = '300s'"))
        names = [r[0] for r in conn.execute(text(EXPORT_SQL))]
    print(f"{len(names):,} given names")
    if args.write:
        DATA_FILE.write_text(render(names), encoding="utf-8")
        print(f"wrote {DATA_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
