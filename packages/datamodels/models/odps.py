"""Open Data Product Standard (ODPS v1.0.0) files for the public API's data contracts (#274).

Every ODCS contract in dbt_project/contracts/ names the data product it belongs to
(``dataProduct``). Each such product gets ``dbt_project/contracts/products/<product>.odps.yaml``:
an ODPS v1.0.0 data product with one output port per contract, pointing at it by ``contractId``.
``python -m models.odcs --write`` writes the products with the contracts, and ``--check`` checks
them too: stale, missing or extra files, validity, and ports whose contract doesn't exist.

v1.0.0 rather than v1.1.0 because Databricks Labs' Ontos bundles the ODPS v1.0.0 JSON Schema.
Products have no input ports: their sources have no contracts.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
SCHEMA_FILE = (
    REPO_ROOT / "dbt_project" / "contracts" / "_schema" / "odps-json-schema-v1.0.0.json"
)
API_VERSION = "v1.0.0"
PRODUCT_VERSION = "1.0.0"
SUBDIR = "products"
SUFFIX = ".odps.yaml"
HEADER = (
    "# Generated by `python -m models.odcs --write` from the ODCS contracts in"
    " dbt_project/contracts/ (issue #274).\n"
    "# Do not edit by hand: change the dbt schema.yml or models.odps.PRODUCTS, then"
    " regenerate.\n"
)

# What each data product is. Its output ports come from the contracts that name it.
PRODUCTS: dict[str, dict[str, Any]] = {
    "open-navigator-public-api": {
        "name": "Open Navigator public API",
        "domain": "civic",
        "description": {
            "purpose": "The tables the Open Navigator public API serves from the `public` "
            "schema, each described by an ODCS data contract.",
            "usage": "Read through the Open Navigator public API. Each output port is one "
            "table; its contractId names the ODCS contract in dbt_project/contracts/ that "
            "gives its columns, keys and quality rules.",
            "limitations": "Lists the served tables that have an enforced dbt contract; the "
            "others are listed in web_docs/docs/development/data-contracts.md. Structure "
            "only: no row counts, freshness or service levels.",
        },
        "tags": ["open-navigator", "public-api"],
    },
}


def _sentence(text: str) -> str:
    """The first sentence of a dbt description, without its ``public.<model> —`` lead-in."""
    text = re.sub(r"^public\.\w+\s*[—–-]+\s*", "", " ".join(str(text).split()))
    found = re.match(
        r"(.*?(?<!\b[A-Za-z])(?<!e\.g)(?<!i\.e)\.)(?:\s|$)", text + " ", re.DOTALL
    )
    sentence = (found.group(1) if found else text).strip()
    return sentence[:1].upper() + sentence[1:]


def _port(contract: dict[str, Any]) -> dict[str, Any]:
    port: dict[str, Any] = {
        "name": contract["name"],
        "version": contract["version"],
        "contractId": contract["id"],
        "type": "table",
    }
    description = _sentence(contract["schema"][0].get("description", ""))
    if description:
        port["description"] = description
    return port


def products_for(contracts: dict[str, dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """One ODPS data product per ``dataProduct`` the contracts name, with a port per contract."""
    groups: dict[str, list[dict[str, Any]]] = {}
    for contract in contracts.values():
        groups.setdefault(contract["dataProduct"], []).append(contract)
    unknown = sorted(set(groups) - set(PRODUCTS))
    if unknown:
        raise ValueError(
            "ODCS contracts name data products that models.odps.PRODUCTS doesn't define: "
            + ", ".join(unknown)
        )
    products: dict[str, dict[str, Any]] = {}
    for product_id, group in groups.items():
        info = PRODUCTS[product_id]
        products[product_id] = {
            "apiVersion": API_VERSION,
            "kind": "DataProduct",
            "id": product_id,
            "name": info["name"],
            "version": PRODUCT_VERSION,
            "status": "active",
            "domain": info["domain"],
            "description": dict(info["description"]),
            "tags": list(info["tags"]),
            "outputPorts": [_port(c) for c in group],
        }
    return products


@lru_cache(maxsize=1)
def _schema() -> dict[str, Any]:
    return json.loads(SCHEMA_FILE.read_text(encoding="utf-8"))


def validate(
    product: dict[str, Any], schema: dict[str, Any] | None = None
) -> list[str]:
    """Every way the product breaks the ODPS v1.0.0 JSON Schema; empty when it is valid."""
    from jsonschema import Draft201909Validator

    validator = Draft201909Validator(schema or _schema())
    return sorted(
        f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.message}"
        for e in validator.iter_errors(product)
    )


def dangling_ports(product: dict[str, Any], contract_ids: set[str]) -> list[str]:
    """The product's output ports whose ``contractId`` matches no contract."""
    return [
        f"{port.get('name')}: contractId {port.get('contractId')!r} matches no contract"
        for port in product.get("outputPorts") or []
        if port.get("contractId") not in contract_ids
    ]
